import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const contract = fileName => new URL('../../../packages/contracts_v2/' + fileName, import.meta.url);
const target = fileName => new URL('../src/generated/' + fileName, import.meta.url);
const raw = JSON.parse(await readFile(contract('openapi.json'), 'utf8'));
const definitions = {};
for (const [route, methods] of Object.entries(raw.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    const success = Object.keys(operation.responses).find(status => /^2\d\d$/.test(status));
    const reference = operation.responses[success].content['application/json'].schema.$ref;
    definitions[operation.operationId] = {
      route, method: method.toUpperCase(), envelope: reference.split('/').at(-1),
      status: Number(success), idempotent: operation['x-idempotency-required'] === true,
    };
  }
}
await mkdir(target(''), { recursive: true });
await writeFile(target('contract.ts'), astToString(await openapiTS(raw)));
await copyFile(contract('schemas.json'), target('schemas.json'));
await writeFile(target('operations.ts'), '// Generated by npm run generate. Do not edit.\n'
  + 'export const basePath = ' + JSON.stringify(raw.servers[0].url) + ';\n'
  + 'export const endpoints = ' + JSON.stringify(definitions, null, 2) + ' as const;\n');
